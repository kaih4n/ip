package sioet.ui;

import sioet.task.Task;
import sioet.task.TaskList;

import java.util.List;
import java.util.Scanner;

/**
 * Handles interactions between sioet.ui.Sioet and the user.
 */
public class Ui {
    private static final String BLUE = "\u001B[34m";
    private static final String GREEN = "\u001B[32m";
    private static final String RESET = "\u001B[0m";

    private final Scanner scanner;
    private String lastResponse = "";

    /**
     * Creates a user interface that reads commands from standard input.
     */
    public Ui() {
        scanner = new Scanner(System.in);
    }

    /**
     * Returns the most recent response generated by the UI.
     *
     * @return the most recent response
     */
    public String getLastResponse() {
        return lastResponse;
    }

    public void showWelcome() {
        String horizontalBorder = "═".repeat(30);
        String banner = "╔" + horizontalBorder + "╗\n"
                + "║%-30s║%n".formatted("      ✦       ･        ✧")
                + bannerLine("   :    ", "╔═╗╦╔═╗╔═╗╔╦╗", "    *")
                + bannerLine("  ﾟ     ", "╚═╗║║ ║║╣  ║", "      ✦")
                + bannerLine("     ✧  ", "╚═╝╩╚═╝╚═╝ ╩", "   ･")
                + "║%-30s║%n".formatted("   *        :       ﾟ     ✧")
                + "╚" + horizontalBorder + "╝\n";

        lastResponse = "Hello! I'm sioet.ui.Sioet.\n"
                + "What can I do for you?";

        System.out.println(banner
                + BLUE + lastResponse + RESET
        );
    }

    private String bannerLine(String prefix, String lettering, String suffix) {
        String content = prefix + lettering + suffix;
        return "║" + prefix + BLUE + lettering + RESET + suffix
                + " ".repeat(30 - content.length()) + "║\n";
    }

    public String readCommand() {
        System.out.print(GREEN + "You: " + RESET);
        System.out.flush();

        if (!scanner.hasNextLine()) {
            return null;
        }

        return scanner.nextLine();
    }

    public void showBye() {
        lastResponse = "Bye! Hope to see you again soon!";
        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showError(String message) {
        lastResponse = "I couldn't do that: " + message;
        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showTaskAdded(Task task, int taskCount) {
        lastResponse = "Got it. I've added this task:\n  " + task
                + "\nNow you have " + taskCount + " tasks in the list.";

        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showTasksDeleted(String deletedTasks,
                                 int numberOfDeletedTasks,
                                 int taskCount) {
        String message = numberOfDeletedTasks == 1
                ? "Noted. I've removed this task:\n\n"
                : "Noted. I've removed these tasks:\n\n";

        lastResponse = message
                + deletedTasks.trim()
                + "\nNow you have "
                + taskCount
                + " tasks in the list.";

        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showTasks(TaskList tasks) {
        StringBuilder response = new StringBuilder(
                "Here are the tasks in your list:\n");

        for (int index = 0; index < tasks.size(); index++) {
            response.append(index + 1)
                    .append(".")
                    .append(tasks.get(index))
                    .append("\n");
        }

        lastResponse = response.toString().trim();

        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showMatchingTasks(List<Task> matchingTasks) {
        if (matchingTasks.isEmpty()) {
            lastResponse = "No matching tasks found.";
            System.out.println(BLUE + lastResponse + RESET);
            return;
        }

        StringBuilder response = new StringBuilder(
                "Here are the matching tasks in your list:\n");

        for (int index = 0; index < matchingTasks.size(); index++) {
            response.append(index + 1)
                    .append(".")
                    .append(matchingTasks.get(index))
                    .append("\n");
        }

        lastResponse = response.toString().trim();

        System.out.println(BLUE + lastResponse + RESET);
    }

    public void showTasksMarked(String markedTasks,
                                int numberOfMarkedTasks,
                                boolean shouldMarkDone) {
        String message;

        if (numberOfMarkedTasks == 1) {
            message = shouldMarkDone
                    ? "Nice! I've marked this task as done:\n\n"
                    : "OK, I've marked this task as not done yet:\n\n";
        } else {
            message = shouldMarkDone
                    ? "Nice! I've marked these tasks as done:\n\n"
                    : "OK, I've marked these tasks as not done yet:\n\n";
        }

        lastResponse = message + markedTasks.trim();

        System.out.println(BLUE + lastResponse + RESET);
    }
}
